import { test, signInSeller } from '../fixtures'
test('grid typing', async ({ page }) => {
  page.on('console', (m) => { if (m.text().includes('grid-debug')) console.log('CONSOLE', m.text()) })
  await signInSeller(page, process.env.E2E_SELLER_EMAIL!, process.env.E2E_SELLER_PASSWORD!)
  await page.goto('/products/create')
  const dlg = page.locator('[role=dialog]').last()
  await dlg.locator('input[name="title"]').fill('Grid probe')
  await dlg.locator('button', { hasText: /^Continue$/ }).click()
  await dlg.locator('button', { hasText: /^Continue$/ }).click()
  const cell = (c: string) => dlg.locator(`[data-container-id="${c}"]`)
  const input = (n: string) => dlg.locator(`input[name="${n}"]`)
  await cell('0:3').click(); await page.keyboard.type('1499'); await page.keyboard.press('Enter'); await page.waitForTimeout(400)
  console.log('RESULT price 1499 =', await input('variants.0.prices.php').inputValue())
  await cell('0:3').click(); await page.keyboard.type('250', { delay: 150 }); await page.keyboard.press('Enter'); await page.waitForTimeout(400)
  console.log('RESULT price retype 250 slow =', await input('variants.0.prices.php').inputValue())
  await cell('0:1').click(); await page.keyboard.type('Blue'); await page.keyboard.press('Enter'); await page.waitForTimeout(400)
  console.log('RESULT title Blue =', await input('variants.0.title').inputValue())
  await cell('0:2').click(); await page.keyboard.type('SKU-1'); await page.keyboard.press('Enter'); await page.waitForTimeout(400)
  console.log('RESULT sku SKU-1 =', await input('variants.0.sku').inputValue())
})
